"""Render local ingestion/dbt configuration from Terraform JSON on stdin."""

import json
import os
from pathlib import Path
import sys
import tempfile


def output_value(outputs, name):
    entry = outputs.get(name)
    value = entry.get("value") if isinstance(entry, dict) else None
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"Terraform output {name!r} must have a nonempty string value")
    return value


def render_template(path, replacements):
    text = path.read_text(encoding="utf-8")
    for token, value in replacements.items():
        if token not in text:
            raise ValueError(f"Missing placeholder {token} in {path}")
        # JSON strings are valid YAML scalars and safely quote the output values.
        text = text.replace(token, json.dumps(value))
    return (
        "# Generated by scripts/save_outputs.sh; edit the .example template instead.\n"
        + text.rstrip() + "\n"
    )


def export_outputs(project_dir, outputs):
    if not isinstance(outputs, dict):
        raise ValueError("Terraform outputs must be a JSON object")
    values = {
        name: output_value(outputs, name)
        for name in (
            "gcp_project_id",
            "gcp_bigquery_raw_ingest_id",
            "gcp_bucket_raw_ingest_id",
            "raw_ingest_source_url",
        )
    }
    project = {"__GCP_PROJECT_ID__": values["gcp_project_id"]}
    dbt_dir = project_dir / "dbt"
    json_text = json.dumps(outputs, indent=2) + "\n"

    # Read and render both templates before staging or replacing any files.
    files = {
        project_dir / "ingestion/outputs.json": json_text,
        dbt_dir / "outputs.json": json_text,
        dbt_dir / "profiles.yml": render_template(dbt_dir / "profiles.yml.example", project),
        dbt_dir / "models/staging/terraform_sources.yml": render_template(
            dbt_dir / "models/staging/sources.yml.example",
            {**project, "__RAW_DATASET_ID__": values["gcp_bigquery_raw_ingest_id"]},
        ),
    }
    staged = []
    try:
        # Stage every file first; each replacement is atomic within its directory.
        for destination, text in files.items():
            with tempfile.NamedTemporaryFile(
                mode="w", encoding="utf-8", dir=destination.parent,
                prefix=f".{destination.name}.", suffix=".tmp", delete=False,
            ) as temporary:
                staged.append((Path(temporary.name), destination))
                temporary.write(text)
        for temporary, destination in staged:
            os.replace(temporary, destination)
            print(f"Saved {destination}")
    finally:
        for temporary, _ in staged:
            temporary.unlink(missing_ok=True)


def main():
    try:
        project_dir = Path(sys.argv[1]).resolve()
        export_outputs(project_dir, json.load(sys.stdin))
    except (OSError, ValueError, IndexError) as error:
        print(f"Output export failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
