-- Show all records with duplicate (dp, sale_date) keys.

WITH duplicates AS (
    SELECT
        dp,
        sale_date,
        COUNT(*) AS duplicate_keys
    FROM {{ source('raw', 'sales_raw') }}
    GROUP BY dp, sale_date
    HAVING COUNT(*) > 1
)

